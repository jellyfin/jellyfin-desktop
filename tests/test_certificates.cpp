void TestCertificates::testVerifyServer()
{
    if (!QSslSocket::supportsSsl())
        QSKIP("No TLS backend available");

    QSslConfiguration serverConfig = QSslConfiguration::defaultConfiguration();
    serverConfig.setLocalCertificate(firstCert(VERIFY_SERVER_PEM));
    serverConfig.setPrivateKey(QSslKey(QByteArray(VERIFY_SERVER_KEY), QSsl::Rsa));
    serverConfig.setPeerVerifyMode(QSslSocket::VerifyNone);

    // Failed PKCS#12 parses must not leave errors behind for Qt's TLS stack
    stage("client", QByteArray::fromBase64(TEST_CLIENT_PBES2_SHA256_PASS_B64), "c.p12", "wrongpass");
    stage("ca", QByteArray::fromBase64(TEST_CA_P12_PBES2_SHA256_PASS_B64), "ca.p12", "wrongpass");
    certs().clearPending();

    QSslServer server;
    server.setSslConfiguration(serverConfig);
    // Any: localhost resolves to ::1 first on macOS
    QVERIFY(server.listen(QHostAddress::Any));
    const QUrl url(QString("https://localhost:%1").arg(server.serverPort()));

    auto verify = [&](const QSslCertificate& expected) {
        int result = -1;
        certs().verifyServer(url, expected, [&result](bool trusted) { result = trusted ? 1 : 0; });
        [&]() { QTRY_VERIFY_WITH_TIMEOUT(result != -1, 15000); }();
        return result == 1;
    };

    // No custom CA for the server
    QCOMPARE(verify(firstCert(VERIFY_SERVER_PEM)), false);

    // The right CA validates the server
    QVERIFY(stage("ca", QByteArray(VERIFY_CA_PEM), "ca.pem")["success"].toBool());
    QVERIFY(certs().commit(url.toString()));
    QCOMPARE(verify(firstCert(VERIFY_SERVER_PEM)), true);

    // Chromium reported a different certificate than the server presents
    QCOMPARE(verify(firstCert(VERIFY_CA_PEM)), false);

    // A different CA with the same subject name must not be trusted
    QVERIFY(certs().remove(url.toString(), "ca"));
    QVERIFY(stage("ca", QByteArray(VERIFY_OTHER_CA_PEM), "other.pem")["success"].toBool());
    QVERIFY(certs().commit(url.toString()));
    QCOMPARE(verify(firstCert(VERIFY_SERVER_PEM)), false);
}

