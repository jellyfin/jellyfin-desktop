static CertificateComponent& certs()
{
    return CertificateComponent::Get();
}

static QVariantMap stage(const QString& kind, const QByteArray& data, const QString& fileName,
                         const QString& password = QString())
{
    return certs().stage(kind, fileName, QString::fromLatin1(data.toBase64()), password);
}

static void writeRaw(const QString& path, const QByteArray& data)
{
    QDir().mkpath(QFileInfo(path).path());
    QFile file(path);
    QVERIFY(file.open(QIODevice::WriteOnly));
    file.write(data);
}

static QSslCertificate firstCert(const char* pem)
{
    return QSslCertificate::fromData(QByteArray(pem), QSsl::Pem).value(0);
}

