void TestCertificates::testDescribeTlsFailure()
{
    const QSslCertificate server = firstCert(VERIFY_SERVER_PEM);
    const QSslCertificate ca = firstCert(VERIFY_CA_PEM);
    const QString fallback = "Qt error text";
    auto describe = [&](const QList<QSslError>& errors, bool clientCert, QNetworkReply::NetworkError error,
                        const QString& text) {
        return CertificateComponent::describeTlsFailure(errors, clientCert, error, text);
    };

    // Wrong or missing CA: the root sent by the server is reported as untrusted
    QString msg = describe({QSslError(QSslError::SelfSignedCertificateInChain, ca)}, true,
                           QNetworkReply::SslHandshakeFailedError, fallback);
    QVERIFY(msg.contains("Verify Test CA"));
    QVERIFY(msg.contains("not trusted"));

    // Only the leaf was sent: its issuer is named
    msg = describe({QSslError(QSslError::UnableToGetLocalIssuerCertificate, server)}, false,
                   QNetworkReply::SslHandshakeFailedError, fallback);
    QVERIFY(msg.contains("Verify Test CA"));

    msg = describe({QSslError(QSslError::HostNameMismatch, server)}, false, QNetworkReply::SslHandshakeFailedError, fallback);
    QVERIFY(msg.contains("localhost"));
    QVERIFY(msg.contains("127.0.0.1"));

    QVERIFY(describe({QSslError(QSslError::CertificateExpired, server)}, false,
                     QNetworkReply::SslHandshakeFailedError, fallback).contains("expired"));

    // Client certificate refused (ghostunnel reports a TLS alert after the handshake)
    const QString alert = "Error while reading: error:0A000418:SSL routines::tlsv1 alert unknown ca";
    msg = describe({}, true, QNetworkReply::UnknownNetworkError, alert);
    QVERIFY(msg.contains("did not accept the client certificate"));
    QVERIFY(msg.contains(alert));
    QVERIFY(describe({}, true, QNetworkReply::RemoteHostClosedError, fallback).contains("client certificate"));

    // Without a client certificate the same failure is not blamed on it
    QCOMPARE(describe({}, false, QNetworkReply::RemoteHostClosedError, fallback), fallback);
    QCOMPARE(describe({}, true, QNetworkReply::ConnectionRefusedError, fallback), fallback);
}

void TestCertificates::testIsCertificateProblem()
{
    const QSslCertificate server = firstCert(VERIFY_SERVER_PEM);
    auto problem = [](const QList<QSslError>& errors, bool clientCert, QNetworkReply::NetworkError error,
                      const QString& text = "Qt error text") {
        return CertificateComponent::isCertificateProblem(errors, clientCert, error, text);
    };

    // Server certificate problems, with or without a client certificate
    for (QSslError::SslError e : {QSslError::SelfSignedCertificateInChain, QSslError::HostNameMismatch,
                                  QSslError::CertificateExpired}) {
        QVERIFY(problem({QSslError(e, server)}, false, QNetworkReply::SslHandshakeFailedError));
        QVERIFY(problem({QSslError(e, server)}, true, QNetworkReply::SslHandshakeFailedError));
    }

    // The server refused the client certificate
    QVERIFY(problem({}, true, QNetworkReply::UnknownNetworkError,
                    "Error while reading: error:0A000418:SSL routines::tlsv1 alert unknown ca"));
    QVERIFY(problem({}, true, QNetworkReply::RemoteHostClosedError));

    // Network errors are retried
    QVERIFY(!problem({}, false, QNetworkReply::ConnectionRefusedError));
    QVERIFY(!problem({}, false, QNetworkReply::RemoteHostClosedError));
    QVERIFY(!problem({}, true, QNetworkReply::ConnectionRefusedError));
    QVERIFY(!problem({}, true, QNetworkReply::HostNotFoundError));
    QVERIFY(!problem({}, false, QNetworkReply::OperationCanceledError));
}

void TestCertificates::testMatchClientCert()
{
    QCOMPARE(certs().matchClientCert({}, "https://localhost:8443"), -1);
    QCOMPARE(certs().matchClientCert({}, ""), -1);

    const QVariant dummy = QVariant::fromValue(firstCert(TEST_CA_PEM));
    QCOMPARE(certs().matchClientCert({dummy}, "https://unknown.host.local:8443"), -1);

    QVERIFY(stage("client", QByteArray::fromBase64(TEST_CLIENT_RSA_P12_NOPASS_B64), "client.p12")["success"].toBool());
    QVERIFY(certs().commit("https://mtls-test.local:8443"));
    const QVariant client = QVariant::fromValue(
        QSslCertificate::fromPath(certs().serverDir(QUrl("https://mtls-test.local:8443")) + "/client.pem").value(0));

    const QVariantList offered = {dummy, client};
    QCOMPARE(certs().matchClientCert(offered, "https://mtls-test.local:8443"), 1);
    QCOMPARE(certs().matchClientCert(offered, "mtls-test.local:8443"), 1);
    QCOMPARE(certs().matchClientCert(offered, "https://mtls-test.local:9443"), -1);
    QCOMPARE(certs().matchClientCert({dummy}, "https://mtls-test.local:8443"), -1);

    // QML passes ClientCertificateOption objects that only expose a few properties
    const QSslCertificate clientCert = client.value<QSslCertificate>();
    QObject dummyOption, clientOption;
    for (auto [option, cert] : {std::pair<QObject*, QSslCertificate>{&dummyOption, dummy.value<QSslCertificate>()},
                                std::pair<QObject*, QSslCertificate>{&clientOption, clientCert}}) {
        option->setProperty("subject", cert.subjectDisplayName());
        option->setProperty("issuer", cert.issuerDisplayName());
        option->setProperty("effectiveDate", cert.effectiveDate());
        option->setProperty("expiryDate", cert.expiryDate());
    }
    QCOMPARE(certs().matchClientCert({QVariant::fromValue(&dummyOption), QVariant::fromValue(&clientOption)},
                                     "//mtls-test.local:8443"), 1);
    QCOMPARE(certs().matchClientCert({QVariant::fromValue(&dummyOption)}, "//mtls-test.local:8443"), -1);

    // A pending client certificate is offered while testing a new server
    QVERIFY(stage("client", QByteArray::fromBase64(TEST_CLIENT_EC_P12_NOPASS_B64), "new.p12")["success"].toBool());
    const QVariant pending = QVariant::fromValue(
        QSslCertificate::fromPath(certs().pendingDir() + "/client.pem").value(0));
    QCOMPARE(certs().matchClientCert({dummy, client, pending}, "https://new-server.local"), 2);
}

